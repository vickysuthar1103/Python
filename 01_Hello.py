print("Hello")  # we can use both single and double quotes for string
print("Hello",144-1,".") # string + number(operation) + string
print("Hello",144-1,sep='|') # string + number(operation) + string, but here we can use sep='|' to separate the values 
print('''Hello,
How are you''') # use Triple quotes(any single or double) for multiline print
print ("Hello, 'vicky'") # used single quote inside double quotes
print ('Hello, \'vicky\'') # use \(backslash) to ignore single quote
print (type(144-1)) # int
print (type("144-1")) # str
print(1,2,3,4,5, sep='-', end='...\n') # numbers with sep and end
